#!/usr/bin/env python3
# Regenerates src/usage.c from the comment block above each cmd_* prototype in
# inc/*.h, so "winspect help <command>" always shows the same text as the
# headers. Run from the repo root after changing a header:
#   python3 tools/gen_usage.py
import re, os, glob
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
main = open(os.path.join(root, 'src', 'main.c'), encoding='utf-8').read()
cmds = re.findall(r'^\s*\{ "([a-z]+)",\s*cmd_([a-z_]+)', main, re.M)
entries = []
for name, fn in cmds:
    text = None
    for h in glob.glob(os.path.join(root, 'inc', '*.h')):
        src = open(h, encoding='utf-8').read()
        m = re.search(r'((?:^//[^\n]*\n)+)int cmd_%s\(' % fn, src, re.M)
        if m:
            # Drop the "// " marker but keep any further indentation (usage
            # lines are indented under their description).
            lines = [l[3:].rstrip() if l.startswith('// ') else l[2:].rstrip()
                     for l in m.group(1).splitlines()]
            text = '\n'.join(lines).strip()
            break
    if text is None:
        raise SystemExit(f'no header comment for cmd_{fn}')
    entries.append((name, text))

def c_str(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"')
    return '\n'.join('        "%s\\n"' % l for l in s.split('\n'))

out = ['// GENERATED by tools/gen_usage.py from the comments in inc/*.h - do not edit.',
       '// "winspect help <command>" / "winspect <command> --help" print these.',
       '',
       '#include "usage.h"',
       '',
       '#include <string.h>',
       '',
       'static const struct { const char *name, *text; } usage_table[] = {']
for name, text in entries:
    out.append('    { "%s",' % name)
    out.append(c_str(text) + ' },')
out += ['};', '',
        'const char *command_usage(const char *name)',
        '{',
        '    for (size_t i = 0; i < sizeof usage_table / sizeof usage_table[0]; i++) {',
        '        if (strcmp(usage_table[i].name, name) == 0) {',
        '            return usage_table[i].text;',
        '        }',
        '    }',
        '    return NULL;',
        '}', '']
open(os.path.join(root, 'src', 'usage.c'), 'w', encoding='utf-8').write('\n'.join(out))
print(f'wrote src/usage.c ({len(entries)} commands)')
